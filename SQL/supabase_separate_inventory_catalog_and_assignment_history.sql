-- Separate Inventory and Paraphernalia item catalogs and track assignment history.
--
-- Paste this entire file into the Supabase SQL Editor and run it once before
-- deploying the updated application. It is safe to rerun and preserves data.

begin;

-- Inventory gets its own catalog. This is a one-time copy of the current
-- Paraphernalia catalog; future changes in either manager stay independent.
create table if not exists public.inventory_equipment_items (
  item_id bigint generated by default as identity primary key,
  item_name text not null unique,
  item_group text not null default 'Security / Safety',
  item_category text not null default 'SEC',
  unit_price numeric not null default 0,
  display_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.inventory_equipment_items
  add column if not exists item_group text default 'Security / Safety',
  add column if not exists item_category text default 'SEC',
  add column if not exists unit_price numeric default 0,
  add column if not exists display_order integer default 0,
  add column if not exists is_active boolean default true,
  add column if not exists created_at timestamptz default now(),
  add column if not exists updated_at timestamptz default now();

delete from public.inventory_equipment_items duplicate
using public.inventory_equipment_items retained
where duplicate.item_id > retained.item_id
  and upper(btrim(duplicate.item_name)) = upper(btrim(retained.item_name));

update public.inventory_equipment_items
set item_name = upper(btrim(item_name)),
    item_group = case
      when item_group in (
        'Communication',
        'Security / Safety',
        'Tactical',
        'Transportation / Mobility',
        'Emergency / Medical',
        'Office Equipment'
      ) then item_group
      when upper(btrim(coalesce(item_category, 'SEC'))) = 'OFFICE' then 'Office Equipment'
      else 'Security / Safety'
    end,
    item_category = case
      when item_group = 'Office Equipment'
        or upper(btrim(coalesce(item_category, 'SEC'))) = 'OFFICE' then 'OFFICE'
      else 'SEC'
    end,
    unit_price = greatest(coalesce(unit_price, 0), 0),
    display_order = coalesce(display_order, 0),
    is_active = coalesce(is_active, true),
    created_at = coalesce(created_at, now()),
    updated_at = coalesce(updated_at, now());

alter table public.inventory_equipment_items
  alter column item_name set not null,
  alter column item_group set default 'Security / Safety',
  alter column item_group set not null,
  alter column item_category set default 'SEC',
  alter column item_category set not null,
  alter column unit_price set default 0,
  alter column unit_price set not null,
  alter column display_order set default 0,
  alter column display_order set not null,
  alter column is_active set default true,
  alter column is_active set not null,
  alter column created_at set default now(),
  alter column created_at set not null,
  alter column updated_at set default now(),
  alter column updated_at set not null;

create unique index if not exists inventory_equipment_items_name_uidx
  on public.inventory_equipment_items (item_name);

create index if not exists inventory_equipment_items_group_order_idx
  on public.inventory_equipment_items (item_group, display_order, item_name);

insert into public.inventory_equipment_items (
  item_name,
  item_group,
  item_category,
  unit_price,
  display_order,
  is_active
)
select
  upper(btrim(pi.item_name)),
  case
    when pi.item_group in (
      'Communication',
      'Security / Safety',
      'Tactical',
      'Transportation / Mobility',
      'Emergency / Medical',
      'Office Equipment'
    ) then pi.item_group
    when upper(btrim(coalesce(pi.item_category, 'SEC'))) = 'OFFICE' then 'Office Equipment'
    else 'Security / Safety'
  end,
  case
    when pi.item_group = 'Office Equipment'
      or upper(btrim(coalesce(pi.item_category, 'SEC'))) = 'OFFICE' then 'OFFICE'
    else 'SEC'
  end,
  greatest(coalesce(pi.unit_price, 0), 0),
  coalesce(pi.display_order, 0),
  coalesce(pi.is_active, true)
from public.paraphernalia_items pi
where nullif(btrim(coalesce(pi.item_name, '')), '') is not null
on conflict (item_name) do nothing;

create table if not exists public.removed_inventory_equipment_items (
  item_name text primary key,
  removed_at timestamptz not null default now()
);

-- Inventory detachment history. Legacy columns are retained so this upgrades
-- the earlier draft migration without deleting any recorded values.
create table if not exists public.inventory_detachment_history (
  id bigint generated by default as identity primary key,
  inventory_id text not null,
  detachment text not null,
  previous_detachment text,
  new_detachment text,
  change_type text not null default 'UPDATED',
  changed_at timestamptz not null default now()
);

alter table public.inventory_detachment_history
  add column if not exists detachment text,
  add column if not exists previous_detachment text,
  add column if not exists new_detachment text,
  add column if not exists change_type text default 'UPDATED',
  add column if not exists changed_at timestamptz default now();

update public.inventory_detachment_history
set new_detachment = coalesce(new_detachment, nullif(btrim(detachment), '')),
    change_type = case
      when upper(btrim(coalesce(change_type, ''))) in ('INITIAL', 'UPDATED', 'CLEARED')
        then upper(btrim(change_type))
      else 'UPDATED'
    end,
    changed_at = coalesce(changed_at, now());

create index if not exists inventory_detachment_history_record_changed_idx
  on public.inventory_detachment_history (inventory_id, changed_at desc);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'inventory_detachment_history_change_type_check'
      and conrelid = 'public.inventory_detachment_history'::regclass
  ) then
    alter table public.inventory_detachment_history
      add constraint inventory_detachment_history_change_type_check
      check (change_type in ('INITIAL', 'UPDATED', 'CLEARED'));
  end if;
end
$$;

create or replace function public.log_inventory_detachment_history()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  previous_value text;
  next_value text;
  next_change_type text;
begin
  if tg_op = 'INSERT' then
    next_value := nullif(btrim(coalesce(new.detachment, '')), '');
    if next_value is not null then
      insert into public.inventory_detachment_history (
        inventory_id, detachment, previous_detachment, new_detachment, change_type, changed_at
      ) values (
        new.id::text, next_value, null, next_value, 'INITIAL', now()
      );
    end if;
    return new;
  end if;

  previous_value := nullif(btrim(coalesce(old.detachment, '')), '');
  next_value := nullif(btrim(coalesce(new.detachment, '')), '');
  if previous_value is not distinct from next_value then
    return new;
  end if;

  next_change_type := case
    when next_value is null then 'CLEARED'
    when previous_value is null then 'INITIAL'
    else 'UPDATED'
  end;

  insert into public.inventory_detachment_history (
    inventory_id, detachment, previous_detachment, new_detachment, change_type, changed_at
  ) values (
    new.id::text,
    coalesce(next_value, previous_value, 'Unassigned'),
    previous_value,
    next_value,
    next_change_type,
    now()
  );
  return new;
end;
$$;

drop trigger if exists inventory_fixed_asset_detachment_history_trigger
  on public.inventory_fixed_asset;

create trigger inventory_fixed_asset_detachment_history_trigger
after insert or update of detachment on public.inventory_fixed_asset
for each row
execute function public.log_inventory_detachment_history();

insert into public.inventory_detachment_history (
  inventory_id, detachment, previous_detachment, new_detachment, change_type, changed_at
)
select
  asset.id::text,
  btrim(asset.detachment),
  null,
  btrim(asset.detachment),
  'INITIAL',
  coalesce(asset.last_updated_at, now())
from public.inventory_fixed_asset asset
where nullif(btrim(coalesce(asset.detachment, '')), '') is not null
  and not exists (
    select 1
    from public.inventory_detachment_history history
    where history.inventory_id = asset.id::text
  );

-- Car Insurance Post/s Distributions history.
create table if not exists public.car_insurance_post_distribution_history (
  id bigint generated by default as identity primary key,
  other_expiration_item_id bigint not null,
  post_distributions text not null,
  previous_post_distributions text,
  new_post_distributions text,
  change_type text not null default 'UPDATED',
  changed_at timestamptz not null default now()
);

alter table public.car_insurance_post_distribution_history
  add column if not exists post_distributions text,
  add column if not exists previous_post_distributions text,
  add column if not exists new_post_distributions text,
  add column if not exists change_type text default 'UPDATED',
  add column if not exists changed_at timestamptz default now();

update public.car_insurance_post_distribution_history
set new_post_distributions = coalesce(new_post_distributions, nullif(btrim(post_distributions), '')),
    change_type = case
      when upper(btrim(coalesce(change_type, ''))) in ('INITIAL', 'UPDATED', 'CLEARED')
        then upper(btrim(change_type))
      else 'UPDATED'
    end,
    changed_at = coalesce(changed_at, now());

create index if not exists car_insurance_post_history_record_changed_idx
  on public.car_insurance_post_distribution_history (other_expiration_item_id, changed_at desc);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'car_insurance_post_history_change_type_check'
      and conrelid = 'public.car_insurance_post_distribution_history'::regclass
  ) then
    alter table public.car_insurance_post_distribution_history
      add constraint car_insurance_post_history_change_type_check
      check (change_type in ('INITIAL', 'UPDATED', 'CLEARED'));
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conname = 'car_insurance_post_history_item_fkey'
      and conrelid = 'public.car_insurance_post_distribution_history'::regclass
  ) and not exists (
    select 1
    from public.car_insurance_post_distribution_history history
    left join public.other_expiration_items item
      on item.id = history.other_expiration_item_id
    where item.id is null
  ) then
    alter table public.car_insurance_post_distribution_history
      add constraint car_insurance_post_history_item_fkey
      foreign key (other_expiration_item_id)
      references public.other_expiration_items(id)
      on update cascade
      on delete cascade;
  end if;
end
$$;

create or replace function public.log_car_insurance_post_distribution_history()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  previous_value text;
  next_value text;
  next_change_type text;
begin
  if upper(btrim(coalesce(new.expiration_type, ''))) <> 'CAR_INSURANCE' then
    return new;
  end if;

  if tg_op = 'INSERT' then
    next_value := nullif(btrim(coalesce(new.post_distributions, '')), '');
    if next_value is not null then
      insert into public.car_insurance_post_distribution_history (
        other_expiration_item_id,
        post_distributions,
        previous_post_distributions,
        new_post_distributions,
        change_type,
        changed_at
      ) values (
        new.id, next_value, null, next_value, 'INITIAL', coalesce(new.created_at, now())
      );
    end if;
    return new;
  end if;

  previous_value := nullif(btrim(coalesce(old.post_distributions, '')), '');
  next_value := nullif(btrim(coalesce(new.post_distributions, '')), '');
  if previous_value is not distinct from next_value then
    return new;
  end if;

  next_change_type := case
    when next_value is null then 'CLEARED'
    when previous_value is null then 'INITIAL'
    else 'UPDATED'
  end;

  insert into public.car_insurance_post_distribution_history (
    other_expiration_item_id,
    post_distributions,
    previous_post_distributions,
    new_post_distributions,
    change_type,
    changed_at
  ) values (
    new.id,
    coalesce(next_value, previous_value, 'Unassigned'),
    previous_value,
    next_value,
    next_change_type,
    now()
  );
  return new;
end;
$$;

drop trigger if exists car_insurance_post_distribution_history_trigger
  on public.other_expiration_items;

create trigger car_insurance_post_distribution_history_trigger
after insert or update of post_distributions on public.other_expiration_items
for each row
execute function public.log_car_insurance_post_distribution_history();

insert into public.car_insurance_post_distribution_history (
  other_expiration_item_id,
  post_distributions,
  previous_post_distributions,
  new_post_distributions,
  change_type,
  changed_at
)
select
  item.id,
  btrim(item.post_distributions),
  null,
  btrim(item.post_distributions),
  'INITIAL',
  coalesce(item.updated_at, item.created_at, now())
from public.other_expiration_items item
where upper(btrim(coalesce(item.expiration_type, ''))) = 'CAR_INSURANCE'
  and nullif(btrim(coalesce(item.post_distributions, '')), '') is not null
  and not exists (
    select 1
    from public.car_insurance_post_distribution_history history
    where history.other_expiration_item_id = item.id
  );

